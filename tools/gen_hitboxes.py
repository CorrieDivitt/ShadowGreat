"""Regenerate src/sg_hitboxes.c from shadowgate-map.toml.

Run after changing any hit box, button or menu choice in the map:
    python tools/gen_hitboxes.py
(Developers only; players never need Python. Needs Python 3.11 or newer.)

It copies three things out of the map (addresses and values we measured,
nothing from the game itself):
  [hitboxes]       -> where each clickable thing is on screen
  [buttons.play]   -> what to write to select a play-screen button
  [screens.*]      -> each menu's choice byte; a choice's value is its
                      position in that screen's `choices` list (0, 1, 2)
"""
import pathlib, tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SCREENS = {  # map table -> SgScreen name in sg_game.h
    "play": "SG_SCREEN_PLAY",
    "file_select": "SG_SCREEN_FILE_SELECT",
    "file_options": "SG_SCREEN_FILE_OPTIONS",
    "game_over": "SG_SCREEN_GAME_OVER",
    "save_confirm": "SG_SCREEN_SAVE_CONFIRM",
}

def cname(s):
    return s.replace(" ", "_")

def main():
    data = tomllib.loads((ROOT / "shadowgate-map.toml").read_text(encoding="utf-8"))
    out = [
        "/* sg_hitboxes.c - GENERATED by tools/gen_hitboxes.py from",
        " * shadowgate-map.toml. Do not edit by hand: edit the map and run the",
        " * script again. */",
        '#include "sg_hitboxes.h"',
        "",
        "/* [hitboxes]: game pixels, edges included */",
        "const SgHitbox sg_hitboxes[] = {",
    ]
    for table, screen in SCREENS.items():
        for name, rects in data["hitboxes"][table].items():
            for l, t, r, b in rects:
                out.append(f'    {{ {screen + ",":<25} "{name}", {l:3}, {t:3}, {r:3}, {b:3} }},')
    out += ["};", "const int sg_hitbox_count = (int)(sizeof sg_hitboxes / sizeof sg_hitboxes[0]);", ""]

    out += ["/* [buttons.play]: cursor X/Y ($AB/$AC), $AD (-1 = leave alone), $AF */",
            "const SgButton sg_buttons[] = {"]
    for name, b in data["buttons"]["play"].items():
        x, y = b["snap"]
        out.append(f'    {{ "{name}", 0x{x:02X}, 0x{y:02X}, {("0x%02X" % b["ad"]) if "ad" in b else "  -1"}, 0x{b["af"]:02X} }},')
    out += ["};", "const int sg_button_count = (int)(sizeof sg_buttons / sizeof sg_buttons[0]);", ""]

    out += ["/* [screens.*]: menu choices; value = position in the choices list */",
            "const SgChoice sg_choices[] = {"]
    for table, screen in SCREENS.items():
        s = data["screens"][table]
        if "choice_byte" not in s:
            continue
        for i, name in enumerate(s["choices"]):
            out.append(f'    {{ {screen + ",":<25} "{cname(name)}", 0x{s["choice_byte"]:04X}, {i} }},')
    out += ["};", "const int sg_choice_count = (int)(sizeof sg_choices / sizeof sg_choices[0]);", ""]

    # Every hit box must lead somewhere: a play button, the scene/map, or a
    # menu choice of its own screen.
    for table in SCREENS:
        names = set(data["hitboxes"][table])
        if table == "play":
            known = set(data["buttons"]["play"]) | {"SCENE", "MAP"}
        else:
            known = {cname(c) for c in data["screens"][table]["choices"]}
        missing = names - known
        if missing:
            raise SystemExit(f"[hitboxes.{table}] has no action for: {sorted(missing)}")

    (ROOT / "src" / "sg_hitboxes.c").write_text("\n".join(out), encoding="utf-8")
    print("wrote src/sg_hitboxes.c")

if __name__ == "__main__":
    main()
