"""Regenerate src/sg_hitboxes.c from the [hitboxes] tables in shadowgate-map.toml.

Run after changing any hit box:   python tools/gen_hitboxes.py
(Developers only; players never need Python. Needs Python 3.11 or newer.)
"""
import pathlib, tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SCREENS = {  # map table -> SgScreen name in sg_game.h
    "play": "SG_SCREEN_PLAY",
    "file_select": "SG_SCREEN_FILE_SELECT",
    "file_options": "SG_SCREEN_FILE_OPTIONS",
    "game_over": "SG_SCREEN_GAME_OVER",
    "save_confirm": "SG_SCREEN_SAVE_CONFIRM",
}

def main():
    data = tomllib.loads((ROOT / "shadowgate-map.toml").read_text(encoding="utf-8"))
    boxes = data["hitboxes"]
    out = [
        "/* sg_hitboxes.c - GENERATED by tools/gen_hitboxes.py from the [hitboxes]",
        " * tables in shadowgate-map.toml. Do not edit by hand: edit the map and",
        " * run the script again. Rectangles are game pixels, edges included. */",
        '#include "sg_hitboxes.h"',
        "",
        "const SgHitbox sg_hitboxes[] = {",
    ]
    for table, screen in SCREENS.items():
        for name, rects in boxes[table].items():
            for l, t, r, b in rects:
                out.append(f'    {{ {screen + ",":<25} "{name}", {l:3}, {t:3}, {r:3}, {b:3} }},')
    out += ["};", "const int sg_hitbox_count = (int)(sizeof sg_hitboxes / sizeof sg_hitboxes[0]);", ""]
    (ROOT / "src" / "sg_hitboxes.c").write_text("\n".join(out), encoding="utf-8")
    print("wrote src/sg_hitboxes.c")

if __name__ == "__main__":
    main()
